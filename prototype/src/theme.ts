// 根级变量同样覆盖挂载到 body 的弹窗与通知，避免浮层脱离配色体系。
export function applyPalette() {
  for (const [key, value] of Object.entries(palette)) {
    document.documentElement.style.setProperty('--' + key.replace(/[A-Z]/g, letter => '-' + letter.toLowerCase()), value)
  }
}

