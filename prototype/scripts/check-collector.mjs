import assert from 'node:assert/strict'
import {collectorPages,collectorDevice,createCollectorFixtures,validateManagement,validateCapture,validateConnection,validateMaintenance} from '../src/data/collector.ts'
import {createFixtures} from '../src/data/fixtures.ts'
import {pageById} from '../src/data/catalog.ts'
import {useCollector} from '../src/composables/useCollector.ts'
const fixture=createCollectorFixtures()
const sensor=createFixtures(pageById.get('sensors')).find(item=>item.id===collectorDevice.id)
assert.equal(sensor.name,collectorDevice.name)
assert.equal(sensor.interface,fixture.capture.interfaces[0])
assert.equal(sensor.version,fixture.engineActive)
assert.equal(sensor.ruleVersion,fixture.ruleActive)
assert.equal(sensor.snapshotAt,collectorDevice.snapshot)
assert.equal(collectorPages.length,5)
assert.equal(new Set(collectorPages.map(page=>page.id)).size,5)
assert.deepEqual(validateManagement(fixture.network,fixture.interfaces,fixture.capture.interfaces),[])
assert.deepEqual(validateCapture(fixture.capture,fixture.interfaces,fixture.network.interface),[])
assert.deepEqual(validateConnection(fixture.connection),[])
assert.deepEqual(validateMaintenance(fixture.maintenance),[])
assert.ok(validateManagement({...fixture.network,interface:'eth0'},fixture.interfaces,fixture.capture.interfaces).some(error=>error.includes('同时')))
assert.ok(validateManagement({...fixture.network,ipv4:'999.20.0.8/24'},fixture.interfaces,fixture.capture.interfaces).length)
assert.ok(validateManagement({...fixture.network,ipv6:'2001:db8:::8/64'},fixture.interfaces,fixture.capture.interfaces).length)
assert.ok(validateManagement({...fixture.network,interface:'eth2'},fixture.interfaces,fixture.capture.interfaces).some(error=>error.includes('链路断开')))
assert.ok(validateCapture({...fixture.capture,interfaces:['eth1']},fixture.interfaces,fixture.network.interface).length)
assert.ok(validateCapture({...fixture.capture,interfaces:['lo']},fixture.interfaces,fixture.network.interface).length)
assert.ok(validateCapture({...fixture.capture,interfaces:['eth0','eth0']},fixture.interfaces,fixture.network.interface).length)
assert.ok(validateCapture({...fixture.capture,snaplen:256},fixture.interfaces,fixture.network.interface).length)
assert.ok(validateCapture({...fixture.capture,interfaces:['eth2'],snaplen:1522},fixture.interfaces,fixture.network.interface).length)
assert.ok(validateConnection({...fixture.connection,host:'999.999.999.999'}).length)
assert.ok(validateConnection({...fixture.connection,artifactUrl:'http://platform.example.test'}).length)
assert.ok(validateConnection({...fixture.connection,artifactUrl:'https://user:password@platform.example.test'}).length)
assert.ok(validateMaintenance({...fixture.maintenance,walGiB:100,pcapGiB:250}).length)
assert.equal(fixture.maintenance.logDays,180)
assert.notEqual(fixture.ruleDesired,fixture.ruleActive)
assert.notEqual(fixture.ruleRollback,fixture.ruleActive)
const model=useCollector()
const before=JSON.stringify({network:model.state.network,capture:model.state.capture,active:model.state.ruleActive,agent:model.state.agentActive})
const task=model.request('network','eth1','网络变更；回滚确认窗口 90 秒；等待执行回执。')
assert.equal(task.status,'等待执行回执')
assert.ok(task.steps.some(step=>step.status==='尚未提供'))
assert.equal(JSON.stringify({network:model.state.network,capture:model.state.capture,active:model.state.ruleActive,agent:model.state.agentActive}),before)
assert.equal(model.state.audits[0].result,'已创建本地申请，未执行')
console.log('采集器校验通过：设备身份、管理/采集口隔离、IPv4/IPv6、采集长度、mTLS 输入、缓冲容量、180 天默认值及申请/实际状态边界。')
